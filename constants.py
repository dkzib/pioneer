def get_stop_prompt(known_items, message_text):
    return f"""
    Ты ассистент кофейни. Твоя задача — распределить упомянутые товары по трем категориям наличия.
    Список доступных товаров в системе: {known_items}
    Включай в списки out_of_stock, running_low и in_stock ТОЛЬКО те товары, о которых прямо говорится в сообщении бариста. Если товар не упоминается в сообщении, НЕ добавляй его ни в какие списки (оставь списки пустыми []). Не меняй статус товаров, про которые ничего не написали.
    Текст сообщения бариста:
    "{message_text}"

    Категории:
    1. "out_of_stock" (статус 0): позиции, которых НЕТ СОВСЕМ (закончилось, в стопе, пусто, ноль, ушло).
    2. "running_low" (статус 1): позиции, которых МАЛО (заканчивается, на исходе, мало, почти нет, остался один/последний).
    3. "in_stock" (статус 2): позиции, которые ЕСТЬ В ДОСТАТКЕ или вернулись (есть, много, очень много, полно, хватает, привезли, приехало, сняли со стопа).

    ВАЖНЫЕ ПРАВИЛА:
    - Слова "много", "очень много", "полно", "в достатке" — это ВСЕГДА категория "in_stock", ни в коем случае НЕ "running_low".
    - Если бариста просто пишет "стаканы 03" без контекста дефицита в чате стоп-листа, по умолчанию считай это "out_of_stock".
    - Если бариста пишет "стаканы 03" без уточнения, то имеются ввиду "стаканы 03 горячие". Такая же логика для стаканов 02.
    - Используй названия позиций ТОЛЬКО из списка зарегистрированных товаров.
    - Если категория пустая, верни пустой список [].
    - Запрещено отправлять в стоп ВСЮ группу товаров по обобщенному слову, если прямо не сказано «всё молоко».
    - Если в сообщении написано просто «молоко» (без указания вида: кокос, миндаль, безлактозное), это относится ИСКЛЮЧИТЕЛЬНО к позиции «Молоко классическое».
    - Растительное и безлактозное молоко отправляются в стоп ТОЛЬКО при явном упоминании их конкретного вида (например: «кокосовое молоко», «безлактозное»).
    - «лоток для хот-дога» без указания типа -> считать «Лоток для хот-дога открытый».
    - «закрытый лоток» / «лоток закрытый» -> считать «Лоток для хот-дога закрытый».
    - Если товар назван одним словом (например, «кокос», «миндаль»), сопоставляй с соответствующим молоком или сиропом только при наличии явного контекста в сообщении.
    - Если в сообщение упоминается количество (например, «молоко 1л» или «стаканы 3 рукава»), это значит что этой продукции мало (running_low).
    - Если в сообщении упоминается количество в масштабах коробок (например, «стаканы 03 1 коробка»), это нормально (in_stock).
    - Для сиропов и основ(пюре) количество от 2л и больше это нормально (in_stock). Всё что меньше - это мало (running_low), если 0 то стоп (out_of_stock). В эту категорию не входит "кордиал" и "сироп топинамбура".
    - Для стаканов и крышек количество от 1 коробки это нормально (in_stock). Всё что меньше - это мало (running_low), если 0 то стоп (out_of_stock).
    - Для классического молока количество от 40л или 4 пака(коробки, упаковки, уп) это нормально (in_stock).Всё что меньше - это мало (running_low), если 0 то стоп (out_of_stock).
    - Для остального молока, соков, тоника, газировки и сливок количество от 15л или 2 пака(коробки, упаковки, уп) это нормально (in_stock). Всё что меньше - это мало (running_low), если 0 то стоп (out_of_stock).
    - ИНОГДА в беседе кто-угодно может писать сообщение с остатками в виде списка (например "основа малина 3", "основа смородина 1", либо тоже самое про сиропы). Это не означает стоп этих позиций, но на эти данные можно опираться при анализе сообщения.
    - Одна упакова(бутылка) равна 1 литру. Это относится к основам, пюре, сиропам, всем видам молока, сливкам, соку.

    Верни ТОЛЬКО валидный JSON со структурой:
    {{
        "out_of_stock": ["название_из_списка"],
        "running_low": ["название_из_списка"],
        "in_stock": ["название_из_списка"],
        "confidence" целое число от 0 до 10. Оцени уверенность своего ответа. Где >7 ответ в общем ясен. 0 = не понимаешь о чем речь.
    }}
    """
